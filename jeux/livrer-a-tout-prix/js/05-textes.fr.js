  function typo(s) {
    return String(s)
      .replace(/ :/g, NBSP + ':')
      .replace(/ ([;!?])/g, NNBSP + '$1')
      .replace(/« /g, '«' + NBSP)
      .replace(/ »/g, NBSP + '»');
  }
  function preparer(v) {
    if (typeof v === 'string') return typo(v);
    if (Array.isArray(v)) return v.map(preparer);
    if (typeof v === 'function') return function (vars) { var r = v(vars); return typeof r === 'string' ? typo(r) : r; };
    return v;
  }
  function enregistrer(dict) {
    var out = {};
    for (var k in dict) if (Object.prototype.hasOwnProperty.call(dict, k)) out[k] = preparer(dict[k]);
    LTP.enregistrerTextes(out);
  }
